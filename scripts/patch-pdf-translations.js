// ── Patcher ─────────────────────────────────────────────────────────────────

function patchLanguage(source, lang, additions) {
  // Find the language block:  "lang": {  ...  },
  // We anchor on `"lang": {` and find its matching closing `},` at the same depth.
  const openMarker = `"${lang}": {`;
  const openIdx = source.indexOf(openMarker);
  if (openIdx === -1) {
    console.warn(`  ⚠ Could not find "${lang}" block — skipping`);
    return { source, added: 0, skipped: 0 };
  }

  // Walk forward to find the matching closing brace
  let depth = 0;
  let i = openIdx + openMarker.length - 1; // at the `{`
  let closeIdx = -1;
  for (; i < source.length; i++) {
    const ch = source[i];
    if (ch === "{") depth++;
    else if (ch === "}") {
      depth--;
      if (depth === 0) { closeIdx = i; break; }
    }
  }
  if (closeIdx === -1) {
    console.warn(`  ⚠ Could not find end of "${lang}" block — skipping`);
    return { source, added: 0, skipped: 0 };
  }

  // The block content (between { and })
  const blockContent = source.slice(openIdx + openMarker.length, closeIdx);

  // Determine which keys are missing
  let added = 0, skipped = 0;
  const newLines = [];
  for (const [k, v] of Object.entries(additions)) {
    const keyRegex = new RegExp(`"${k}"\\s*:`);
    if (keyRegex.test(blockContent)) { skipped++; continue; }
    // Escape backslashes and double quotes for safe JS string literal
    const safeVal = String(v).replace(/\\/g, "\\\\").replace(/"/g, '\\"');
    newLines.push(`    "${k}": "${safeVal}",`);
    added++;
  }

  if (added === 0) {
    return { source, added: 0, skipped };
  }

  // Insert the new lines just before the closing `}`.
  // Find the last newline before closeIdx so we insert on its own lines.
  const insertion = "\n" + newLines.join("\n") + "\n  ";
  const before = source.slice(0, closeIdx);
  const after = source.slice(closeIdx);
  const trimmedBefore = before.replace(/\s*$/, ""); // strip trailing whitespace
  const ensureComma = trimmedBefore.endsWith(",") || trimmedBefore.endsWith("{")
    ? trimmedBefore
    : trimmedBefore + ",";

  const next = ensureComma + insertion + after;
  return { source: next, added, skipped };
}

// ── Main ────────────────────────────────────────────────────────────────────
function main() {
  if (!fs.existsSync(FILE)) {
    console.error(`File not found: ${FILE}`);
    process.exit(1);
  }

  let source = fs.readFileSync(FILE, "utf8");
  const original = source;

  console.log(`Patching: ${FILE}`);
  console.log(`Mode: ${DRY ? "DRY RUN (no write)" : "WRITE"}\n`);

  let totalAdded = 0;
  let totalSkipped = 0;

  for (const [lang, additions] of Object.entries(PDF_KEYS)) {
    const before = source;
    const { source: next, added, skipped } = patchLanguage(source, lang, additions);
    source = next;
    totalAdded += added;
    totalSkipped += skipped;
    const verb = added > 0 ? `+${added}` : "—";
    console.log(`  ${lang}: ${verb} added, ${skipped} already present`);
  }

  console.log(`\nTotal: +${totalAdded} keys added, ${totalSkipped} already present`);

  if (source === original) {
    console.log("No changes needed — file unchanged.");
    return;
  }

  if (DRY) {
    console.log("\nDry run — file NOT written. Run without --dry-run to apply.");
    return;
  }

  // Backup
  const backupPath = `${FILE}.backup.${Date.now()}.js`;
  fs.writeFileSync(backupPath, original, "utf8");
  console.log(`Backup written to: ${backupPath}`);

  fs.writeFileSync(FILE, source, "utf8");
  console.log("✓ File updated.");
}

main();